const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const http = require('node:http');
const { _electron } = require('playwright');
const root = path.resolve(__dirname, '..');
const packaged = process.env.BTK_DESKTOP_TEST_EXE;
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'aegis-image-ui-'));
const requests = [];
let app, server, image;
(async () => {
  server = http.createServer(async (req, res) => {
    let body = ''; for await (const part of req) body += part;
    const payload = JSON.parse(body); requests.push({ url: req.url, payload });
    if (payload.prompt?.startsWith('wait for cancel')) return;
    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify(req.url.endsWith('/images/generations') ? { data: [{ b64_json: image.split(',')[1] }] }
      : { choices: [{ message: { content: 'The image contains a green square and red stripe.' }, finish_reason: 'stop' }] }));
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const env = { ...process.env };
  for (const key of Object.keys(env)) if (/BTK|MCP|OPENAI|ANTHROPIC|TOKEN|SECRET|API_KEY|ELECTRON_RUN_AS_NODE/i.test(key)) delete env[key];
  const launch = async () => {
    app = await _electron.launch({ executablePath: packaged || path.join(root, 'node_modules/electron/dist/electron.exe'), args: [...(packaged ? [] : [root]), `--user-data-dir=${profile}`], env });
    const page = await app.firstWindow(); page.setDefaultTimeout(15000);
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.waitForFunction(() => Boolean(window.btk));
    return page;
  };
  let page = await launch();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.evaluate(async port => {
    await window.btk.personal.mode('personal');
    await window.btk.personal.save({ provider: 'local', endpoint: `http://127.0.0.1:${port}/v1`, model: 'fixture-vision', maxTokens: 512 });
  }, server.address().port);
  await page.reload();
  image = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 256; canvas.height = 256;
    const context = canvas.getContext('2d'); context.fillStyle = '#167c65'; context.fillRect(0, 0, 256, 256);
    context.fillStyle = '#e15662'; context.fillRect(70, 0, 50, 256);
    return canvas.toDataURL('image/png');
  });
  const setApproval = async response => app.evaluate(({ dialog }, response) => { dialog.showMessageBox = async (...args) => { global.imageDialog = args.at(-1); return { response }; }; }, response);
  const send = async text => { await page.getByLabel('개인 메시지', { exact: true }).fill(text); await page.getByRole('button', { name: '개인 메시지 전송', exact: true }).click(); };
  const oversized = Buffer.from(image.split(',')[1], 'base64'); oversized.writeUInt32BE(100000, 16); oversized.writeUInt32BE(100000, 20);
  await page.getByLabel('소스 추가', { exact: true }).setInputFiles({ name: 'oversized.png', mimeType: 'image/png', buffer: oversized });
  await page.getByRole('alert').filter({ hasText: '읽을 수 없는' }).waitFor();
  assert.equal(await page.locator('.workspace-source-chips li').count(), 0);
  const rejected = await page.evaluate(async value => { try { await window.btk.personal.chat([{ role: 'user', content: 'inspect', images: [value] }], 'default'); return false; } catch { return true; } }, `data:image/png;base64,${oversized.toString('base64')}`);
  assert.equal(rejected, true); assert.equal(requests.length, 0);
  await page.getByLabel('소스 추가', { exact: true }).setInputFiles({ name: 'reference.png', mimeType: 'image/png', buffer: Buffer.from(image.split(',')[1], 'base64') });
  await page.locator('.workspace-source-chips').getByText('reference.png').waitFor();
  await setApproval(0); await send('Describe the image');
  await page.getByRole('alert').filter({ hasText: '취소' }).waitFor();
  assert.equal(requests.length, 0);
  await setApproval(1); await send('Describe the image');
  await page.getByText('The image contains a green square and red stripe.', { exact: true }).waitFor();
  assert.equal(requests.length, 1);
  assert.equal(requests[0].payload.messages.at(-1).content[1].image_url.url, image);
  assert.equal(await app.evaluate(() => global.imageDialog.defaultId), 0);
  const approvalDetail = await app.evaluate(() => global.imageDialog.detail);
  assert.ok(approvalDetail.includes('fixture-vision') && !approvalDetail.includes('base64'));
  await page.locator('button.new-chat').click();
  await page.getByLabel('출력', { exact: true }).selectOption('image');
  await page.getByLabel('이미지 모델 ID', { exact: true }).fill('fixture-image');
  await send('Generate a green square');
  const generated = page.locator('.personal-message.assistant img');
  await generated.waitFor();
  assert.ok(await generated.evaluate(img => img.complete && img.naturalWidth === 256));
  assert.deepEqual(await generated.evaluate(img => {
    const canvas = document.createElement('canvas'); canvas.width = 256; canvas.height = 256;
    const context = canvas.getContext('2d'); context.drawImage(img, 0, 0);
    return [...context.getImageData(10, 10, 1, 1).data, ...context.getImageData(90, 10, 1, 1).data];
  }), [22, 124, 101, 255, 225, 86, 98, 255]);
  assert.equal(requests[1].url, '/v1/images/generations');
  assert.equal(requests[1].payload.model, 'fixture-image');
  const filePath = path.join(profile, 'saved-image.png');
  await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ filePath }); }, filePath);
  await page.locator('.personal-message.assistant').getByRole('button', { name: '파일 저장', exact: true }).click();
  await page.locator('.workspace-message-images').getByRole('status').waitFor();
  assert.deepEqual(fs.readFileSync(filePath), Buffer.from(image.split(',')[1], 'base64'));
  fs.mkdirSync(path.join(root, 'artifacts'), { recursive: true });
  await page.screenshot({ path: path.join(root, 'artifacts/images-desktop.png') });
  await page.getByLabel('개인 메시지', { exact: true }).fill('unsent image draft');
  await app.close();
  page = await launch(); page.on('pageerror', error => errors.push(error.message));
  await page.locator('.personal-message.assistant img').waitFor();
  assert.equal(await page.getByLabel('이미지 모델 ID', { exact: true }).inputValue(), 'fixture-image');
  assert.equal(await page.getByLabel('개인 메시지', { exact: true }).inputValue(), 'unsent image draft');
  assert.ok(!fs.readFileSync(path.join(profile, 'agent-ops-personal/workspace.enc')).includes(Buffer.from(image)));
  await setApproval(1); await send('wait for cancel');
  await page.getByRole('button', { name: '개인 답변 중단', exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('.personal-pending'));
  await page.waitForTimeout(100);
  await page.getByRole('button', { name: '개인 답변 중단', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '취소' }).waitFor();
  assert.equal(await page.locator('.personal-message.assistant img').count(), 1);
  await page.getByLabel('언어 / Language').selectOption('en');
  await page.getByLabel('Image model ID', { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 760 });
  await page.waitForTimeout(150);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(root, 'artifacts/images-mobile.png') });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.evaluate(() => window.btk.personal.connection('codex'));
  const blocked = await page.evaluate(async () => { try { await window.btk.personal.generateImage([{ role: 'user', content: 'draw' }], 'default', 'fixture-image'); return false; } catch (error) { return error.message.includes('image_unsupported'); } });
  assert.equal(blocked, true);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ status: 'passed', packaged: Boolean(packaged), checks: ['oversized dimensions rejected before decode and IPC transmission', 'declined approval makes zero calls', 'vision request image bytes', 'explicit generation model', 'rendered image pixels', 'save exact PNG', 'encrypted image restart', 'cancel generation', 'English/mobile layout', 'Codex generation unsupported'], fixtureRequests: requests.length, realProviderCalls: 0 }));
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  await app?.close(); server?.closeAllConnections(); if (server?.listening) await new Promise(resolve => server.close(resolve));
});
